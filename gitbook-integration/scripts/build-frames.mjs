// Compiles the demo frame (frame/, with its demos in frame/demos/) and writes
// everything the integration serves into src/generated/assets.ts: the JS
// chunks, the CSS and the fonts. GitBook's CLI then bundles that module into
// the integration.
import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const pkg = join(root, 'node_modules/@ai-atlaas/pixel-foundry/dist');
const THEME = 'night-garden';

const demos = JSON.parse(await readFile(join(root, 'frame/demos/demos.json'), 'utf8'));

// `virtual:demos` gives the frame the demo list and one lazy import per demo,
// so each demo becomes its own small chunk next to a shared vendor chunk.
const virtualDemos = {
  name: 'virtual-demos',
  setup(b) {
    b.onResolve({ filter: /^virtual:demos$/ }, () => ({ path: 'demos', namespace: 'virtual' }));
    b.onLoad({ filter: /.*/, namespace: 'virtual' }, () => ({
      resolveDir: join(root, 'frame/demos'),
      loader: 'js',
      contents: [
        `export const demos = ${JSON.stringify(demos)};`,
        'export const loaders = {',
        ...demos.map((d) => `  ${JSON.stringify(d.id)}: () => import(${JSON.stringify(`./${d.id}.tsx`)}),`),
        '};',
      ].join('\n'),
    }));
  },
};

const result = await build({
  absWorkingDir: root,
  entryPoints: { main: 'frame/main.tsx' },
  bundle: true,
  splitting: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  jsx: 'automatic',
  jsxImportSource: 'react',
  define: { 'process.env.NODE_ENV': '"production"' },
  entryNames: '[name]-[hash]',
  chunkNames: '[name]-[hash]',
  outdir: 'out',
  write: false,
  legalComments: 'none',
  plugins: [virtualDemos],
});

const assets = {};
let mainScript = '';
for (const file of result.outputFiles) {
  const name = basename(file.path);
  assets[name] = { type: 'text/javascript; charset=utf-8', encoding: 'utf8', body: file.text };
  if (name.startsWith('main-')) mainScript = name;
}

// The page lives at <endpoint>/frame, so fonts are served from <endpoint>/assets/.
const fonts = ['pixelify-latin.ttf', 'plex-latin.ttf'];
for (const font of fonts) {
  const bytes = await readFile(join(pkg, 'fonts', font));
  assets[font] = { type: 'font/ttf', encoding: 'base64', body: bytes.toString('base64') };
}
const styles = (await readFile(join(pkg, 'styles.css'), 'utf8')).replaceAll('./fonts/', 'assets/');
const theme = await readFile(join(pkg, 'themes', `${THEME}.css`), 'utf8');
const frameCss = await readFile(join(root, 'frame/frame.css'), 'utf8');

const out = join(root, 'src/generated/assets.ts');
await mkdir(dirname(out), { recursive: true });
await writeFile(
  out,
  [
    '// Generated by scripts/build-frames.mjs. Do not edit.',
    `export const demos: { id: string; title: string; height: number; top?: boolean }[] = ${JSON.stringify(demos)};`,
    `export const mainScript = ${JSON.stringify(mainScript)};`,
    `export const css = ${JSON.stringify(`${styles}\n${theme}\n${frameCss}`)};`,
    `export const assets: Record<string, { type: string; encoding: 'utf8' | 'base64'; body: string }> = ${JSON.stringify(assets)};`,
    '',
  ].join('\n'),
);

const kb = (n) => `${(n / 1024).toFixed(1)} kB`;
for (const [name, a] of Object.entries(assets)) console.log(`  ${name.padEnd(28)} ${kb(a.body.length)}`);
console.log(`Wrote src/generated/assets.ts (${demos.length} demo${demos.length === 1 ? '' : 's'})`);
